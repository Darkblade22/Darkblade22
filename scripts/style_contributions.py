"""Apply the profile palette to the generated contribution graph, preserving data."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
source = root / "profile-3d-contrib/profile-night-view.svg"
target = root / "profile-3d-contrib/profile-darkblade.svg"
svg = source.read_text()
svg = svg.replace("#00000f", "#0b0b0c").replace("#eeeeff", "#f4f4f5")
svg = svg.replace("rgb(255,200,55)", "#d4d4d8")
levels = [(38, 31, 25), (83, 65, 51), (125, 102, 80), (180, 145, 110), (244, 195, 149)]
for level, shades in enumerate(levels):
    for side, shade in zip(("top", "left", "right"), shades):
        pattern = rf"(\.cont-{side}-{level}\s*\{{\s*fill:)\s*[^;]+;"
        svg = re.sub(pattern, rf"\g<1> rgb({shade},{shade},{shade});", svg)
svg = svg.replace(
    '<svg xmlns="http://www.w3.org/2000/svg"',
    '<svg role="img" aria-labelledby="title desc" xmlns="http://www.w3.org/2000/svg"',
    1,
)
svg = svg.replace(
    "><style>",
    '><title id="title">Darkblade22 — GitHub contributions</title>'
    '<desc id="desc">Actual contribution data generated by GitHub Profile 3D Contrib, in monochrome.</desc><style>',
    1,
)
target.write_text(svg)
print(f"Styled contribution graph: {target.name}")
